def test_gemini_provider_unconfigured():
    with patch("app.ai.providers.gemini.ai_config") as mock_cfg:
        mock_cfg.GEMINI_API_KEY = None
        with pytest.raises(AINotConfiguredException):
            GeminiProvider()

def test_gemini_provider_generate_mocked():
    with patch("app.ai.providers.gemini.ai_config") as mock_cfg:
        mock_cfg.GEMINI_API_KEY = "test_gemini_key_123"
        provider = GeminiProvider()

    mock_json_response = {
        "candidates": [
            {
                "content": {
                    "parts": [{"text": "Strategic marketing plan generated by Gemini."}],
                    "role": "model"
                },
                "finishReason": "STOP"
            }
        ],
        "usageMetadata": {
            "promptTokenCount": 25,
            "candidatesTokenCount": 50,
            "totalTokenCount": 75
        }
    }

    mock_http_response = MagicMock()
    mock_http_response.status_code = 200
    mock_http_response.json.return_value = mock_json_response

    with patch("httpx.Client.post", return_value=mock_http_response):
        messages = [
            AIRequestMessage(role="system", content="You are a marketing strategist."),
            AIRequestMessage(role="user", content="Analyze our growth trajectory.")
        ]
        response = provider.generate(messages=messages, model="gemini-1.5-flash")

        assert response.content == "Strategic marketing plan generated by Gemini."
        assert response.info.provider == "gemini"
        assert response.info.model == "gemini-1.5-flash"
        assert response.info.input_tokens == 25
        assert response.info.output_tokens == 50
        assert response.info.total_tokens == 75

def test_ai_cmo_agent_initialization():
    agent = AICMOAgent()
    assert agent.agent_id == "ai_cmo"
    assert "strategic_planning" in agent.capabilities
    assert agent.definition.category == "CORE"

def test_ai_cmo_agent_execution_and_persistence():
    db = SessionLocal()
    try:
        # Create test workspace and brand
        ws = Workspace(name="AI CMO Test Workspace", slug="ai-cmo-test-ws")
        db.add(ws)
        db.commit()

        brand = Brand(workspace_id=ws.id, name="Test Brand Corp", website_url="https://testbrand.com")
        db.add(brand)
        db.commit()

        context = AgentContext(
            run_id=uuid.uuid4(),
            workspace_id=ws.id,
            brand_id=brand.id,
            user_id=uuid.uuid4(),
            brand_context=None
        )

        agent = AICMOAgent()
        result = agent.execute(context)

        assert result.status == "COMPLETED"
        assert "summary" in result.output_data
        assert "strategic_pillars" in result.output_data
        assert len(result.output_data["strategic_pillars"]) > 0
        assert len(result.output_data["opportunities"]) > 0

        # Verify opportunities were persisted to the database
        db_opps = db.query(Opportunity).filter(Opportunity.brand_id == brand.id).all()
        assert len(db_opps) >= 1
        assert any(o.source == "AI_CMO" for o in db_opps)

    finally:
        # Cleanup
        try:
            db.query(Opportunity).filter(Opportunity.brand_id == brand.id).delete()
            db.query(Brand).filter(Brand.id == brand.id).delete()
            db.query(Workspace).filter(Workspace.id == ws.id).delete()
            db.commit()
        except Exception:
            db.rollback()
        db.close()
